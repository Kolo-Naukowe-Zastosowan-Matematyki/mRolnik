/**
 * Zwraca uprawę po ID lub nazwie (case-insensitive).
 */
export function findCrop(query) {
  if (!query) return null;
  const q = String(query).trim().toLowerCase();
  return (
    POLISH_CROPS.find(
      (c) => c.id.toLowerCase() === q || c.name.toLowerCase() === q
    ) || null
  );
}

/**
 * Zwraca grupę retencyjną dla danej uprawy.
 */
export function getCropRetentionGroup(query) {
  if (!query) return null;
  if (RETENTION_GROUPS[query]) return RETENTION_GROUPS[query];
  const crop = findCrop(query);
  if (!crop) return null;
  const gId = crop.retention_group_id || crop.group_id;
  return RETENTION_GROUPS[gId] || null;
}

/**
 * Filtruje uprawy po fragmencie tekstu (nazwa, kategoria, grupa retencyjna).
 */
export function filterCrops(searchQuery) {
  const q = String(searchQuery || '').trim().toLowerCase();
  if (!q) return POLISH_CROPS.slice();
  return POLISH_CROPS.filter(
    (c) =>
      c.name.toLowerCase().includes(q) ||
      c.category.toLowerCase().includes(q) ||
      (RETENTION_GROUPS[c.retention_group_id] &&
        RETENTION_GROUPS[c.retention_group_id].name.toLowerCase().includes(q))
  );
}
